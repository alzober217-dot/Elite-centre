function readInitialLanguage() {
  try {
    return window.localStorage.getItem(languageStorageKey) === 'en' ? 'en' : 'ar'
  } catch {
    return 'ar'
  }
}

export function LocaleProvider({ children }) {
  const [language, setLanguage] = useState(readInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
    document.documentElement.dataset.language = language
  }, [language])

  const changeLanguage = useCallback((nextLanguage) => {
    if (!['ar', 'en'].includes(nextLanguage)) throw new Error('Unsupported language.')
    try {
      window.localStorage.setItem(languageStorageKey, nextLanguage)
    } catch {
      throw new Error(english['أخفق حفظ الإعداد على هذا الجهاز.'])
    }
    setLanguage(nextLanguage)
  }, [])

  const translate = useCallback((text) => language === 'en' ? english[text] ?? text : text, [language])
  const value = useMemo(() => ({ language, changeLanguage, t: translate }), [language, changeLanguage, translate])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useLocale must be used within LocaleProvider.')
  return context
}
